import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

// Wrap the single-file build (dist/index.html) into a TS string module that
// React Native can import. RN can't import .html directly, so RichEditor
// imports `editorHtml` and passes it to useEditorBridge({ customSource }).
const here = dirname(fileURLToPath(import.meta.url));
const htmlPath = resolve(here, '../dist/index.html');
const outPath = resolve(here, '../../src/generated/editorHtml.ts');

const html = readFileSync(htmlPath, 'utf8');

const out =
  '// AUTO-GENERATED by web-editor build. Do not edit by hand.\n' +
  '// Regenerate with: cd web-editor && yarn build\n' +
  'export const editorHtml: string = ' +
  JSON.stringify(html) +
  ';\n';

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, out, 'utf8');

console.log(
  `emit-html: wrote ${outPath} (${(out.length / 1024).toFixed(1)} KB)`
);
